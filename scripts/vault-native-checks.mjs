import assert from 'node:assert/strict';
import { credentials, fixturePassword } from './vault-fixture.mjs';

export async function vaultNativeChecks({ shell, a, b, invoke, check, fixture, action, connect, routeBrowsers }) {
  const url = 'https://accounts.google.com/ServiceLogin';
  const html = '<!doctype html><form><input id="user" autocomplete="username"><input id="pass" type="password"><button>Submit</button></form><script>window.submitted=false;document.querySelector("form").onsubmit=e=>{e.preventDefault();window.submitted=true;}</script>';
  await a.route('https://accounts.google.com/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: html }));
  await a.goto(url);
  assert.equal((await invoke(shell, 'vault_status')).unlocked, false);
  await invoke(shell, 'vault_configure', { server: '' });
  assert.equal((await invoke(shell, 'vault_status')).server, null);
  await assert.rejects(invoke(shell, 'vault_unlock', { input: credentials }), /server URL/);
  await assert.rejects(invoke(shell, 'vault_configure', { server: 'http://vault.example.com' }), /HTTPS/);
  await invoke(shell, 'vault_configure', { server: 'https://vault.example.com/' });
  assert.equal((await invoke(shell, 'vault_status')).server, 'https://vault.example.com');
  await assert.rejects(invoke(shell, 'vault_unlock', { input: { ...credentials, code: '' } }), /two-factor/);
  await invoke(shell, 'vault_unlock', { input: credentials });
  assert.equal((await invoke(shell, 'vault_status')).unlocked, true);
  assert.equal(new Set(fixture.state.devices).size, 1);
  check('Native Rust prelogin, password hash, authenticator challenge, authenticated sync and stable device identity');
  let matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  assert.deepEqual(await invoke(shell, 'vault_availability', { id: 'fixture-a' }), { unlocked: true, hasMatches: true });
  assert.deepEqual(await invoke(shell, 'vault_availability', { id: 'fixture-b' }), { unlocked: true, hasMatches: false });
  assert.deepEqual(await invoke(shell, 'vault_availability', { id: null }), { unlocked: true, hasMatches: false });
  assert.deepEqual(matches.entries.map(e => e.id), ['login', 'item-key']);
  assert.equal(matches.origin, 'https://accounts.google.com');
  assert.equal(matches.skipped, 3);
  assert.ok(!JSON.stringify(matches).includes(fixturePassword));
  assert.ok(!JSON.stringify(matches).includes('synthetic-access'));
  await invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'item-key' });
  assert.equal(await a.locator('#user').inputValue(), 'bob@example.invalid');
  assert.equal(await a.locator('#pass').inputValue(), fixturePassword);
  assert.equal(await a.evaluate(() => window.submitted), false);
  assert.ok(b.url().includes('127.0.0.1'));
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'item-key' }), /again/);
  check('Native autofill decrypts item key, safely transfers quoted Unicode credentials to one view, never submits; selection is single use');
  for (const cmd of ['vault_status', 'vault_availability', 'vault_configure', 'vault_unlock', 'vault_lock', 'vault_matches', 'vault_fill']) {
    assert.equal(await a.evaluate(cmd => window.__TAURI_INTERNALS__.invoke(cmd, { server: 'https://evil.example', input: { email: 'x', password: 'x', code: '' }, id: 'fixture-a', ticket: 'x', entry: 'login' }).then(() => false, () => true), cmd), true);
  }
  check('Remote native route denied all vault commands');
  await a.evaluate(() => { const popup = window.open('about:blank'); popup.location.href = 'http://127.0.0.1:7890/popup'; });
  await new Promise(r => setTimeout(r, 500));
  const popupBrowser = await connect(9223); routeBrowsers.push(popupBrowser);
  const popup = popupBrowser.contexts().flatMap(c => c.pages()).find(p => p.url().includes('/popup'));
  assert.ok(popup);
  assert.equal(await popup.evaluate(() => window.__TAURI_INTERNALS__.invoke('vault_status').then(() => false, () => true)), true);
  await popup.close();
  check('Native service popup denied vault access');
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await a.goto(`${url}?changed=1`);
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'login' }), /changed/);
  assert.equal(await a.locator('#pass').inputValue(), '');
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'other' }), /match/);
  check('Navigation and nonmatching entry reject native fills');
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await a.locator('form').evaluate(form => { form.action = 'https://evil.example'; });
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'login' }), /different origin/);
  assert.equal(await a.locator('#pass').inputValue(), '');
  check('Cross-origin form action rejected without filling');
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await invoke(shell, 'vault_configure', { server: 'https://other.example.com/subpath' });
  assert.equal((await invoke(shell, 'vault_status')).unlocked, false);
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'login' }), /again/);
  check('Saving a different server locks the vault and invalidates fill selection');
  await invoke(shell, 'vault_configure', { server: 'https://vault.example.com' });
  await invoke(shell, 'vault_lock');
  fixture.state.tamper = true;
  await invoke(shell, 'vault_unlock', { input: credentials });
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'login' }), /integrity/);
  check('Altered ciphertext rejected by native MAC verification');
  fixture.state.tamper = false;
  matches = await invoke(shell, 'vault_matches', { id: 'fixture-a' });
  await action(shell, 'fixture-a', 'hibernate');
  await assert.rejects(invoke(shell, 'vault_fill', { ticket: matches.ticket, entry: 'item-key' }), /expired/);
  check('Destroyed view generation invalidates fill');
  await invoke(shell, 'vault_lock');
  fixture.state.delay = 1000;
  const pending = invoke(shell, 'vault_unlock', { input: credentials });
  await new Promise(r => setTimeout(r, 300));
  await invoke(shell, 'vault_configure', { server: 'https://other.example.com' });
  await assert.rejects(pending, /cancelled/);
  assert.equal((await invoke(shell, 'vault_status')).unlocked, false);
  check('Server change invalidates a concurrent unlock and clears session');
}
